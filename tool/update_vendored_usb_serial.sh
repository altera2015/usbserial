#!/usr/bin/env bash
# Vendors mik3y/usb-serial-for-android (MIT) into the plugin so apps don't
# need the JitPack repository.
#
#   tool/update_vendored_usb_serial.sh            # re-vendor the pinned version
#   tool/update_vendored_usb_serial.sh 3.13.0     # bump to another release tag
#   tool/update_vendored_usb_serial.sh --check    # CI: verify the vendored copy
#                                                 # is exactly upstream + rename
#
# The only modification is the package rename
#   com.hoho.android.usbserial -> dev.bessems.usbserial.vendored
# so the copy can never clash with an app that also depends on
# usb-serial-for-android directly.

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
dest="$repo_root/android/src/main/java/dev/bessems/usbserial/vendored"
proguard="$repo_root/android/proguard-rules.pro"
version_file="$dest/VERSION"

upstream_pkg='com.hoho.android.usbserial'
vendored_pkg='dev.bessems.usbserial.vendored'

check=0
tag=""
for arg in "$@"; do
  case "$arg" in
    --check) check=1 ;;
    -h | --help)
      sed -n '2,13p' "$0"
      exit 0
      ;;
    *) tag="$arg" ;;
  esac
done
if [[ -z "$tag" ]]; then
  if [[ ! -f "$version_file" ]]; then
    echo "error: no version given and $version_file missing" >&2
    exit 2
  fi
  tag="$(tr -d '[:space:]' <"$version_file")"
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

echo "Fetching mik3y/usb-serial-for-android $tag ..."
curl -sSfL "https://github.com/mik3y/usb-serial-for-android/archive/refs/tags/$tag.tar.gz" |
  tar xz -C "$work"
src="$work/usb-serial-for-android-$tag"
lib="$src/usbSerialForAndroid"

out="$work/out"
mkdir -p "$out"
cp -R "$lib/src/main/java/com/hoho/android/usbserial/." "$out/"
cp "$src/LICENSE.txt" "$out/LICENSE.txt"
printf '%s\n' "$tag" >"$out/VERSION"

# Rename the package in declarations, imports and fully-qualified references.
find "$out" -name '*.java' -print0 |
  xargs -0 perl -pi -e "s/\Q$upstream_pkg\E/$vendored_pkg/g"

# Upstream's Gradle module generates BuildConfig; some drivers reference
# BuildConfig.DEBUG for a test-only hook. Provide it with the value that
# upstream's published (release) artifacts have.
cat >"$out/BuildConfig.java" <<EOF
// Generated by tool/update_vendored_usb_serial.sh. Stands in for the
// BuildConfig that upstream's Gradle module generates. DEBUG matches the
// value in upstream's published release artifacts.
package $vendored_pkg;

public final class BuildConfig {
    public static final boolean DEBUG = false;

    private BuildConfig() {}
}
EOF

# Upstream ships a consumer keep rule (UsbSerialProber uses reflection to call
# each driver's static getSupportedDevices()). Carry it over, renamed.
{
  echo "# Generated by tool/update_vendored_usb_serial.sh from"
  echo "# mik3y/usb-serial-for-android $tag usbSerialForAndroid/proguard-rules.pro"
  grep -v '^\s*#' "$lib/proguard-rules.pro" | grep -v '^\s*$' |
    perl -pe "s/\Q$upstream_pkg\E/$vendored_pkg/g"
} >"$work/proguard-rules.pro"

if ((check)); then
  status=0
  diff -ru "$out" "$dest" || status=1
  diff -u "$work/proguard-rules.pro" "$proguard" || status=1
  if ((status)); then
    echo "FAIL: vendored usb-serial-for-android differs from upstream $tag" >&2
    echo "      (run tool/update_vendored_usb_serial.sh and commit the result)" >&2
    exit 1
  fi
  echo "OK: vendored usb-serial-for-android matches upstream $tag"
  exit 0
fi

rm -rf "$dest"
mkdir -p "$dest"
cp -R "$out/." "$dest/"
cp "$work/proguard-rules.pro" "$proguard"

echo "Vendored usb-serial-for-android $tag into ${dest#"$repo_root"/}"
echo "Check upstream's usbSerialForAndroid/build.gradle for dependency changes:"
grep -E "^\s*(implementation|api)\s" "$lib/build.gradle" | sed 's/^/  /' || true
